def extract_title(markdown: str) -> Optional[str]:
    """Extracts the H1 title from markdown, ignoring the fixed brief prefix."""
    for line in markdown.splitlines():
        line = line.strip()
        if line.startswith("# "):
            clean = line.replace("# ", "").replace("🧭 ContextPilot Implementation Brief:", "").strip()
            return clean
    return None


def brief_from_markdown(
    request: BriefRequest,
    raw_text: str,
    mode: GenerationMode,
    summary: str,
    repository_status: Optional[str] = None,
) -> ImplementationBrief:
    """Wraps raw AI Markdown in the standard brief object used by the UI."""
    repo_notice = repository_status or build_repo_notice(request)
    return ImplementationBrief(
        title=extract_title(raw_text) or "Software Implementation Brief",
        summary=summary,
        project_type=request.project_type,
        task_scope=request.task_scope,
        mode_used=mode,
        generated_at=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        architecture_overview="See full AI generated Markdown brief.",
        proposed_file_changes=[],
        implementation_steps=[],
        acceptance_criteria=[],
        testing_checklist={},
        security_and_pitfalls=[],
        repository_status=repo_notice,
        is_repo_scanned=bool(request.repo_path and os.path.isdir(request.repo_path.strip())),
        raw_markdown_override=raw_text,
    )