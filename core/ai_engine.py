"""Optional AI-powered implementation brief generation using Google Gemini API.

Transparently integrates with Gemini using the official google-genai SDK when
a GEMINI_API_KEY is configured, while strictly redacting all keys from logs, UI,
and error messages.
"""

from datetime import datetime
import os
import re
from typing import Optional, Tuple

from core.models import (
    BriefRequest,
    GenerationMode,
    ImplementationBrief,
    ProjectType,
    TaskScope,
)


def _sanitize_string(text: str, key_to_redact: Optional[str] = None) -> str:
    """Removes any API key patterns or provided key from strings."""
    if not text:
        return ""
    cleaned = str(text)
    if key_to_redact and key_to_redact.strip():
        cleaned = cleaned.replace(key_to_redact.strip(), "[REDACTED_API_KEY]")
    # Redact Google API key format (AIzaSy...)
    cleaned = re.sub(r"AIza[0-9A-Za-z-_]{35}", "[REDACTED_API_KEY]", cleaned)
    return cleaned


def is_ai_available(custom_key: Optional[str] = None) -> Tuple[bool, str]:
    """Checks whether an API key is configured either via parameter or environment."""
    if custom_key is not None:
        key = custom_key.strip()
    else:
        key = os.getenv("GEMINI_API_KEY", "").strip()

    if not key:
        return False, "No Gemini API key found. Provide one in the sidebar or set the GEMINI_API_KEY environment variable."
    return True, "API Key detected (in-memory / environment)."


def generate_ai_brief(request: BriefRequest) -> ImplementationBrief:
    """Invokes Google Gemini to generate a tailored, professional implementation brief.

    Raises:
        ValueError: If API key is missing.
        RuntimeError: If the Gemini API invocation fails.
    """
    if request.gemini_api_key is not None:
        key = request.gemini_api_key.strip()
    else:
        key = os.getenv("GEMINI_API_KEY", "").strip()

    if not key:
        raise ValueError("Missing Gemini API Key. Please provide a key in the settings or set GEMINI_API_KEY.")

    try:
        from google import genai
        from google.genai import types
        from google.genai.errors import APIError, ClientError
    except ImportError as e:
        raise RuntimeError(f"The 'google-genai' package is not installed: {e}")

    system_instruction = (
        "You are ContextPilot AI, an elite Principal Software Architect and Staff Engineer. "
        "Your task is to transform software development tasks into clear, "
        "production-grade, testable implementation briefs. "
        "Always be practical, concise, and technically rigorous. "
        "Focus on exact files, architecture patterns, actionable acceptance criteria, "
        "and concrete testing checklists. "
        "CRITICAL: Always explicitly note that suggested files are synthesized architectural "
        "recommendations unless an existing repository was explicitly confirmed."
    )

    repo_notice = (
        f"Connected to local repository at '{request.repo_path}'"
        if (request.repo_path and os.path.isdir(request.repo_path.strip()))
        else "Unconnected / Synthesized (No local repository was scanned)"
    )

    user_prompt = f"""
Please generate a comprehensive, highly actionable Implementation Brief for the following task:

**Software Task**:
{request.task_description}

**Project Type / Tech Stack**:
{request.project_type.value}

**Task Scope**:
{request.task_scope.value}

**Repository Context**:
{repo_notice}

Generate the brief in Markdown following this exact structure:
# 🧭 ContextPilot Implementation Brief: [Descriptive Concise Title]

> **Generated by ContextPilot AI**  
> **Mode**: `AI-Powered Engine (Gemini API)` | **Timestamp**: `{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}`  
> **Project Type**: `{request.project_type.value}` | **Scope**: `{request.task_scope.value}`  
> **Repository Context**: `{repo_notice}`

> ⚠️ **Notice**: *ContextPilot synthesized these architectural file paths based on standard project conventions. No local repository was scanned.*

---

## 1. Executive Summary & Problem Scope
[Clear problem statement, goals, and non-goals]

## 2. Architecture & File Structure Strategy
[Architectural approach, components affected, data flows]
### Proposed Files / Components (Architectural Blueprint — Proposed based on standard project conventions, not scanned from disk)
```text
- path/to/file1 (Description of change)  [Synthetic Blueprint — Not scanned from disk]
- path/to/file2 (Description of change)  [Synthetic Blueprint — Not scanned from disk]
```

## 3. Step-by-Step Implementation Plan
### Step 1: [Step Title]
[Actionable description]
**Target Files**: `path/to/file`
**Key Tasks:**
- [ ] Task 1
- [ ] Task 2

[Continue with subsequent steps...]

## 4. Acceptance Criteria
[Numbered acceptance criteria in Given/When/Then or checklist format: AC-1, AC-2, etc.]
- [ ] **[AC-1]** ...
- [ ] **[AC-2]** ...

## 5. Testing & Quality Assurance Checklist
### Unit Tests
- [ ] Test 1
- [ ] Test 2

### Integration & API Tests
- [ ] Test 1
- [ ] Test 2

### Edge Cases & Resiliency
- [ ] Edge case 1
- [ ] Edge case 2

## 6. Risks, Edge Cases & Security Considerations
- ⚠️ Risk or security item 1
- ⚠️ Risk or security item 2

---
*Generated with [ContextPilot AI](https://github.com/alan-ai/contextpilot) — Turning vague software ideas into production-ready briefs.*
"""

    client = genai.Client(api_key=key)

    # Try primary model gemini-2.5-flash with fallback to gemini-2.0-flash
    models_to_try = ["gemini-2.5-flash", "gemini-2.0-flash"]
    last_error: Optional[Exception] = None
    raw_text: str = ""

    for model_name in models_to_try:
        try:
            response = client.models.generate_content(
                model=model_name,
                contents=user_prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction,
                    temperature=0.3,
                ),
            )
            raw_text = response.text or ""
            if raw_text.strip():
                break
        except Exception as exc:
            last_error = exc
            # If it's an auth error (bad key), don't retry with another model
            err_str = str(exc)
            if "API_KEY_INVALID" in err_str or "API key not valid" in err_str:
                break
            continue

    if not raw_text.strip():
        if last_error:
            sanitized_err = _sanitize_string(str(last_error), key)
            if "API_KEY_INVALID" in sanitized_err or "API key not valid" in sanitized_err:
                raise RuntimeError("Gemini API invocation failed: The provided Gemini API key is invalid. Please check your key at https://aistudio.google.com/.")
            if "RESOURCE_EXHAUSTED" in sanitized_err or "429" in sanitized_err:
                raise RuntimeError("Gemini API invocation failed: Rate limit or quota exceeded. Please wait a moment before trying again or switch to the Rule-Based engine.")
            raise RuntimeError(f"Gemini API invocation failed: {sanitized_err}")
        raise RuntimeError("Gemini returned an empty response. Please adjust your prompt and try again.")

    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    title_match = re_title(raw_text) or "Software Implementation Brief"

    return ImplementationBrief(
        title=title_match,
        summary="AI-generated comprehensive brief generated via Gemini API.",
        project_type=request.project_type,
        task_scope=request.task_scope,
        mode_used=GenerationMode.AI_POWERED,
        generated_at=now_str,
        architecture_overview="See full AI generated Markdown brief.",
        proposed_file_changes=[],
        implementation_steps=[],
        acceptance_criteria=[],
        testing_checklist={},
        security_and_pitfalls=[],
        repository_status=repo_notice,
        is_repo_scanned=bool(request.repo_path and os.path.isdir(request.repo_path.strip())),
        raw_markdown_override=raw_text,
    )


def re_title(markdown: str) -> Optional[str]:
    """Helper to extract the H1 title from markdown."""
    for line in markdown.splitlines():
        line = line.strip()
        if line.startswith("# "):
            clean = line.replace("# ", "").replace("🧭 ContextPilot Implementation Brief:", "").strip()
            return clean
    return None
