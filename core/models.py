"""Data models and enums for ContextPilot AI."""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
import os
from typing import Dict, List, Optional


class ProjectType(str, Enum):
    PYTHON = "Python (FastAPI / Flask / Django / Script)"
    JAVA_SPRING = "Java / Spring Boot (REST / Microservice)"
    WEB_APP = "Web Application (React / Next.js / TypeScript / Node)"
    MOBILE = "Mobile (Flutter / Android / iOS)"
    OTHER = "General / Other"

    @classmethod
    def get_display_names(cls) -> List[str]:
        return [item.value for item in cls]

    @classmethod
    def from_display_name(cls, name: str) -> "ProjectType":
        for item in cls:
            if item.value == name:
                return item
        return cls.OTHER


class TaskScope(str, Enum):
    FEATURE = "New Feature / Capability"
    BUGFIX = "Bug Fix / Patch"
    REFACTOR = "Refactoring & Performance Optimization"
    INTEGRATION = "Third-Party API / Service Integration"
    INFRASTRUCTURE = "DevOps / Infrastructure / CI-CD"

    @classmethod
    def get_display_names(cls) -> List[str]:
        return [item.value for item in cls]

    @classmethod
    def from_display_name(cls, name: str) -> "TaskScope":
        for item in cls:
            if item.value == name:
                return item
        return cls.FEATURE


class GenerationMode(str, Enum):
    RULE_BASED = "Rule-Based Deterministic Engine (Offline)"
    AI_POWERED = "AI-Powered Engine (Gemini API)"


@dataclass
class BriefRequest:
    task_description: str
    project_type: ProjectType = ProjectType.PYTHON
    task_scope: TaskScope = TaskScope.FEATURE
    gemini_api_key: Optional[str] = None
    force_ai: bool = False
    repo_path: Optional[str] = None

    def validate(self) -> List[str]:
        """Validates the input parameters. Returns list of error messages."""
        errors = []
        clean_text = (self.task_description or "").strip()
        if not clean_text:
            errors.append("Task description cannot be empty. Please enter the software task details.")
        elif len(clean_text) < 10:
            errors.append("Task description is too brief. Provide at least 10 characters so a meaningful brief can be formed.")

        if self.repo_path and self.repo_path.strip():
            clean_repo = self.repo_path.strip()
            if not os.path.isdir(clean_repo):
                errors.append(f"Specified repository path does not exist or is not a directory: '{clean_repo}'")

        return errors


@dataclass
class ImplementationStep:
    step_number: int
    title: str
    description: str
    target_files: List[str] = field(default_factory=list)
    key_tasks: List[str] = field(default_factory=list)


@dataclass
class ImplementationBrief:
    title: str
    summary: str
    project_type: ProjectType
    task_scope: TaskScope
    mode_used: GenerationMode
    generated_at: str
    architecture_overview: str
    proposed_file_changes: List[str]
    implementation_steps: List[ImplementationStep]
    acceptance_criteria: List[str]
    testing_checklist: Dict[str, List[str]]  # categories: "Unit Tests", "Integration Tests", "Edge Cases"
    security_and_pitfalls: List[str]
    repository_status: str = "Unconnected / Synthesized (No local repository was scanned)"
    is_repo_scanned: bool = False
    scanned_matches: List[str] = field(default_factory=list)
    detected_project_type: Optional[ProjectType] = None
    stack_conflict_warning: Optional[str] = None
    raw_markdown_override: Optional[str] = None

    def to_markdown(self) -> str:
        """Renders the implementation brief as professional Markdown."""
        if self.raw_markdown_override:
            return self.raw_markdown_override

        lines: List[str] = []
        lines.append(f"# 🧭 ContextPilot Implementation Brief: {self.title}")
        lines.append("")
        lines.append(f"> **Generated by ContextPilot AI**  ")
        lines.append(f"> **Mode**: `{self.mode_used.value}` | **Timestamp**: `{self.generated_at}`  ")
        lines.append(f"> **Project Type**: `{self.project_type.value}` | **Scope**: `{self.task_scope.value}`  ")
        lines.append(f"> **Repository Context**: `{self.repository_status}`")
        if self.stack_conflict_warning:
            lines.append(f"> ⚠️ **Stack Mismatch Alert**: {self.stack_conflict_warning}")
        lines.append("")
        if not self.is_repo_scanned:
            lines.append("> ⚠️ **Notice**: *ContextPilot did not scan or inspect a local repository for this brief. The proposed file paths and components below are synthesized architectural recommendations based on standard project conventions.*")
        else:
            lines.append(f"> 🔍 **Notice**: *ContextPilot inspected local repository at `{self.repository_status}`. Files verified on disk are labeled accordingly.*")
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("## 1. Executive Summary & Problem Scope")
        lines.append(self.summary.strip())
        lines.append("")
        lines.append("## 2. Architecture & File Structure Strategy")
        lines.append(self.architecture_overview.strip())
        lines.append("")
        if self.proposed_file_changes:
            status_label = "Verified against local repository" if self.is_repo_scanned else "Architectural Blueprint — Proposed based on standard project conventions, not scanned from disk"
            lines.append(f"### Proposed Files / Components ({status_label})")
            lines.append("```text")
            for f in self.proposed_file_changes:
                lines.append(f"- {f}")
            lines.append("```")
            lines.append("")

        lines.append("## 3. Step-by-Step Implementation Plan")
        for step in self.implementation_steps:
            lines.append(f"### Step {step.step_number}: {step.title}")
            lines.append(step.description.strip())
            lines.append("")
            if step.target_files:
                lines.append(f"**Target Files**: `{'`, `'.join(step.target_files)}`")
                lines.append("")
            if step.key_tasks:
                lines.append("**Key Tasks:**")
                for task in step.key_tasks:
                    lines.append(f"- [ ] {task}")
                lines.append("")

        lines.append("## 4. Acceptance Criteria")
        lines.append("Every criterion below must be satisfied before marking this task complete:")
        lines.append("")
        for ac in self.acceptance_criteria:
            lines.append(f"- [ ] **[AC-{self.acceptance_criteria.index(ac)+1}]** {ac}")
        lines.append("")

        lines.append("## 5. Testing & Quality Assurance Checklist")
        for category, items in self.testing_checklist.items():
            lines.append(f"### {category}")
            for item in items:
                lines.append(f"- [ ] {item}")
            lines.append("")

        if self.security_and_pitfalls:
            lines.append("## 6. Risks, Edge Cases & Security Considerations")
            for pitfall in self.security_and_pitfalls:
                lines.append(f"- ⚠️ {pitfall}")
            lines.append("")

        lines.append("---")
        lines.append("*Generated with [ContextPilot AI](https://github.com/alan-ai/contextpilot) — Turning vague software ideas into production-ready briefs.*")
        return "\n".join(lines)
